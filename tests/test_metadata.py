"""Strict red tests for the federated metadata lifecycle.

Ten defect tests map one-to-one to the ten defects listed in README.md.  Five
additional tests cover the positive path, expiry rejection, entity mismatch,
duplicate writes, and batch equivalence.  Do not edit this file.
"""

import hashlib
import hmac
import json

from meta import (
    check_entity_id,
    check_signature,
    check_validity,
    evict,
    metadata_batch,
    parse_metadata,
    refresh_needed,
    store,
)


NOW = 1_000_000
KEY = b"federation-metadata-signing-key"
ENTITY = "https://idp.example.org/metadata"
OTHER_ENTITY = "https://idp.example.net/metadata"
SSO = "https://idp.example.org/sso"

POLICY = {
    "skew": 0,
    "refresh_before": 60,
    "max_age": 3600,
}


class AlwaysEqual(str):
    """A string whose equality operator claims to match everything."""

    def __eq__(self, other):
        return True

    __hash__ = str.__hash__


def canonical_payload(metadata):
    body = {
        "entity_id": metadata["entity_id"],
        "keys": metadata["keys"],
    }
    return json.dumps(
        body,
        ensure_ascii=False,
        sort_keys=True,
        separators=(",", ":"),
    ).encode("utf-8")


def signature_for(metadata, key=KEY):
    return hmac.new(key, canonical_payload(metadata), hashlib.sha256).hexdigest()


def make_metadata(
    entity_id=ENTITY,
    valid_from=NOW - 1000,
    valid_until=NOW + 1000,
    sso=SSO,
    keys=None,
    covered=None,
    key=KEY,
):
    if keys is None:
        keys = [
            {
                "key_id": "signing-1",
                "use": "signing",
                "value": "certificate-one",
            }
        ]
    metadata = {
        "entity_id": entity_id,
        "valid_from": valid_from,
        "valid_until": valid_until,
        "keys": keys,
        "endpoints": {"sso": sso},
        "signature": {
            "covered": ["entity_id", "keys"] if covered is None else list(covered),
            "value": "",
        },
    }
    metadata["signature"]["value"] = signature_for(metadata, key)
    return metadata


def empty_store():
    return {"entities": {}, "keys": {}, "index": {}}


def batch_request(request_id, metadata, expected=None, key=KEY):
    return {
        "request_id": request_id,
        "metadata": json.dumps(metadata, ensure_ascii=False),
        "expected_entity_id": metadata["entity_id"] if expected is None else expected,
        "key": key,
    }


def test_valid_metadata_passes_all_checks():
    original = make_metadata()
    parsed = parse_metadata(json.dumps(original, ensure_ascii=False))

    assert parsed["entity_id"] == ENTITY
    assert parsed["valid_from"] == NOW - 1000
    assert parsed["valid_until"] == NOW + 1000
    assert parsed["keys"][0]["key_id"] == "signing-1"
    assert parsed["endpoints"]["sso"] == SSO
    assert check_validity(parsed, NOW, 0) is True
    assert check_entity_id(parsed, ENTITY) is True
    assert check_signature(parsed, KEY) is True
    assert refresh_needed(
        {"metadata": parsed, "fetched_at": NOW - 1}, NOW, POLICY
    ) is False


def test_defect01_signature_must_cover_entity_id_and_keys():
    keys_only = make_metadata(covered=["keys"])
    assert check_signature(keys_only, KEY) is False

    entity_only = make_metadata(covered=["entity_id"])
    assert check_signature(entity_only, KEY) is False

    complete = make_metadata()
    assert check_signature(complete, KEY) is True

    tampered_entity = make_metadata()
    tampered_entity["entity_id"] = OTHER_ENTITY
    assert check_signature(tampered_entity, KEY) is False

    tampered_keys = make_metadata()
    tampered_keys["keys"][0]["value"] = "certificate-evil"
    assert check_signature(tampered_keys, KEY) is False


def test_defect02_validity_rejects_metadata_past_valid_until():
    expired = make_metadata(valid_from=NOW - 2000, valid_until=NOW - 1)
    assert check_validity(expired, NOW, 0) is False


def test_defect03_validity_skew_is_applied_exactly_once():
    metadata = make_metadata(valid_from=NOW, valid_until=NOW + 1000)

    assert check_validity(metadata, NOW - 10, 10) is True
    assert check_validity(metadata, NOW - 11, 10) is False
    assert check_validity(metadata, NOW + 1000, 10) is True
    assert check_validity(metadata, NOW + 1001, 10) is False


def test_defect04_entity_id_match_is_exact():
    metadata = {"entity_id": ENTITY}

    assert check_entity_id(metadata, ENTITY) is True
    assert check_entity_id(metadata, ENTITY + "-staging") is False
    assert check_entity_id(metadata, "https://idp.example.org") is False
    assert check_entity_id({"entity_id": ENTITY + "-staging"}, ENTITY) is False


def test_defect05_refresh_uses_validity_not_cache_presence():
    fresh = make_metadata(valid_from=NOW - 100, valid_until=NOW + 1000)
    assert refresh_needed(
        {"metadata": fresh, "fetched_at": NOW - 1}, NOW, POLICY
    ) is False

    near_expiry = make_metadata(valid_from=NOW - 100, valid_until=NOW + 30)
    assert refresh_needed(
        {"metadata": near_expiry, "fetched_at": NOW - 1}, NOW, POLICY
    ) is True

    expired = make_metadata(valid_from=NOW - 100, valid_until=NOW - 1)
    assert refresh_needed(
        {"metadata": expired, "fetched_at": NOW - 1}, NOW, POLICY
    ) is True

    stale = make_metadata(valid_from=NOW - 100, valid_until=NOW + 1000)
    assert refresh_needed(
        {"metadata": stale, "fetched_at": NOW - 4000}, NOW, POLICY
    ) is True


def test_defect06_duplicate_entity_id_does_not_overwrite():
    first = make_metadata()
    second = make_metadata(
        sso="https://attacker.example.net/sso",
        keys=[
            {
                "key_id": "signing-2",
                "use": "signing",
                "value": "certificate-two",
            }
        ],
    )

    current = store(empty_store(), first, NOW)
    returned = store(current, second, NOW)

    assert len(returned["entities"]) == 1
    assert returned["entities"][ENTITY]["endpoints"]["sso"] == SSO
    assert returned["entities"][ENTITY]["keys"][0]["key_id"] == "signing-1"
    assert returned["index"] == {"signing-1": ENTITY}


def test_defect07_evict_clears_entity_index():
    metadata = make_metadata(valid_from=NOW - 100, valid_until=NOW + 10)
    current = store(empty_store(), metadata, NOW)
    assert current["index"] == {"signing-1": ENTITY}

    removed = evict(current, NOW + 11)

    assert removed == 1
    assert ENTITY not in current["entities"]
    assert current["index"] == {}


def test_defect08_evict_removes_key_descriptors():
    metadata = make_metadata(valid_from=NOW - 100, valid_until=NOW + 10)
    current = store(empty_store(), metadata, NOW)
    assert ENTITY in current["keys"]

    removed = evict(current, NOW + 11)

    assert removed == 1
    assert ENTITY not in current["keys"]
    assert current["keys"] == {}


def test_defect09_batch_does_not_reuse_first_entity():
    first = make_metadata(entity_id=ENTITY, sso=SSO)
    second = make_metadata(
        entity_id=OTHER_ENTITY,
        sso="https://idp.example.net/sso",
    )
    requests = [
        batch_request("first", first),
        batch_request("second", second),
    ]

    result = metadata_batch(requests, POLICY, NOW)

    assert result == {"first": True, "second": True}


def test_defect10_signature_comparison_rejects_forged_equal_value():
    valid = make_metadata()
    assert check_signature(valid, KEY) is True

    forged = make_metadata()
    forged["signature"]["value"] = AlwaysEqual("not-the-expected-digest")
    assert check_signature(forged, KEY) is False


def test_expired_metadata_is_rejected():
    metadata = make_metadata(valid_from=NOW, valid_until=NOW + 1)

    assert check_validity(metadata, NOW, 0) is True
    assert check_validity(metadata, NOW + 1, 0) is True
    assert check_validity(metadata, NOW + 2, 0) is False

    current = store(empty_store(), metadata, NOW + 2)
    assert ENTITY not in current["entities"]


def test_entity_id_mismatch_is_rejected():
    metadata = make_metadata()

    assert check_entity_id(metadata, "https://other.example.org/metadata") is False


def test_duplicate_write_is_rejected():
    first = make_metadata(valid_from=NOW - 100, valid_until=NOW + 100)
    current = store(empty_store(), first, NOW)

    duplicate = make_metadata(
        valid_from=NOW - 100,
        valid_until=NOW + 5000,
        sso="https://idp.example.org/replacement",
    )
    returned = store(current, duplicate, NOW)

    assert returned["entities"][ENTITY]["valid_until"] == NOW + 100
    assert returned["entities"][ENTITY]["endpoints"]["sso"] == SSO
    assert list(returned["entities"]) == [ENTITY]
    assert returned["index"] == {"signing-1": ENTITY}


def test_batch_results_match_individual_validation():
    valid = make_metadata(entity_id=ENTITY)
    mismatch = make_metadata(
        entity_id=OTHER_ENTITY,
        sso="https://idp.example.net/sso",
    )
    expired = make_metadata(
        entity_id="https://expired.example.org/metadata",
        valid_from=NOW - 1000,
        valid_until=NOW - 1,
        sso="https://expired.example.org/sso",
    )
    requests = [
        batch_request("valid", valid),
        batch_request("mismatch", mismatch, expected=ENTITY),
        batch_request("expired", expired),
    ]
    expected = {"valid": True, "mismatch": False, "expired": False}

    first_pass = metadata_batch(requests, POLICY, NOW)
    second_pass = metadata_batch(list(reversed(requests)), POLICY, NOW)

    assert first_pass == expected
    assert second_pass == expected

    for item in requests:
        metadata = json.loads(item["metadata"])
        individually_valid = (
            check_validity(metadata, NOW, POLICY["skew"])
            and check_entity_id(metadata, item["expected_entity_id"])
            and check_signature(metadata, item["key"])
        )
        assert first_pass[item["request_id"]] is individually_valid